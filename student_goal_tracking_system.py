def update_progress(student_id):

    print("\n========== UPDATE PROGRESS ==========")

    goal_id = int(input("Enter goal ID: "))
    progress = int(input("Enter progress (0-100): "))

    if progress < 0 or progress > 100:
        print("Progress must be between 0 and 100.")
        return

    if progress == 100:
        status = "Completed"
    else:
        status = "Pending"

    cursor.execute("""
    UPDATE goals
    SET progress = ?, status = ?
    WHERE goal_id = ? AND student_id = ?
    """,
    (progress, status, goal_id, student_id))

    conn.commit()

    if cursor.rowcount > 0:
        print("\nProgress updated successfully!")

    else:
        print("\nGoal not found.")

