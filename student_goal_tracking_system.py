def dashboard(student_id):

    cursor.execute("""
    SELECT
        COUNT(*) AS total_goals,
        SUM(CASE WHEN status = 'Completed' THEN 1 ELSE 0 END),
        SUM(CASE WHEN status = 'Pending' THEN 1 ELSE 0 END),
        COALESCE(AVG(progress), 0)
    FROM goals
    WHERE student_id = ?
    """, (student_id,))

    result = cursor.fetchone()

    total_goals = result[0]
    completed_goals = result[1] or 0
    pending_goals = result[2] or 0
    average_progress = result[3]

    print("\n====================================")
    print("       STUDENT GOAL DASHBOARD")
    print("====================================")

    print("Total Goals       :", total_goals)
    print("Completed Goals   :", completed_goals)
    print("Pending Goals     :", pending_goals)
    print("Average Progress  :", round(average_progress), "%")

    print("====================================")

dashboard(student_id)

